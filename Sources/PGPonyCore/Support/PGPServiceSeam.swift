// CORE SEAM: in the app, PGPService is the orchestration layer (several
// thousand lines over SwiftData models, the Keychain and ObjectivePGP), and it
// stays there. The core code lifted in 8.4.0 calls a handful of its members.
// This file gives those calls a home with the same names, so a lifted file
// reads the same in both trees:
//
// - Copied verbatim from the app: the Cv25519 scalar byte-order resolution,
//   the v6 secret-key unlock (`decryptV6SecretKeyMaterial`, Argon2 or
//   iterated-and-salted S2K plus AEAD, RFC 9580 section 3.7.2.1) and the
//   error enum.
// - Forwarded to the host: picking and unlocking a signing or certification
//   key out of a secret ring (`extractEd25519SigningKey`,
//   `extractPrimaryCertificationKey`, `extractPrimaryRSACertificationKey`).
//   Those walk the app's v4 and v6 secret-packet parsers, which are not part
//   of the core yet. A host that never sets `secretKeyUnlock` gets
//   `.unlockUnavailable` from them, and every path that needs no unlock works
//   as before.

import Foundation
import CryptoKit

final class PGPService {
    static let shared = PGPService()
    private init() {}

    /// The host's secret-key unlock, for the three extractors below.
    struct SecretKeyUnlock {
        var signingKey: (_ secretRing: Data, _ passphrase: String?, _ preferSigningSubkey: Bool) throws -> Ed25519SigningInfo
        var primaryCertificationKey: (_ secretRing: Data, _ passphrase: String?) throws -> Ed25519SigningInfo
        var primaryRSACertificationKey: (_ secretRing: Data, _ passphrase: String?) throws -> RSASigningInfo
    }

    /// Set once by the host at launch. Nil in the standalone core.
    nonisolated(unsafe) static var secretKeyUnlock: SecretKeyUnlock?

    func extractEd25519SigningKey(fromSecretKeyData privData: Data, passphrase: String? = nil, preferSigningSubkey: Bool = true) throws -> Ed25519SigningInfo {
        guard let unlock = Self.secretKeyUnlock else { throw PGPServiceError.unlockUnavailable }
        return try unlock.signingKey(privData, passphrase, preferSigningSubkey)
    }

    func extractPrimaryCertificationKey(fromSecretKeyData data: Data, passphrase: String? = nil) throws -> Ed25519SigningInfo {
        guard let unlock = Self.secretKeyUnlock else { throw PGPServiceError.unlockUnavailable }
        return try unlock.primaryCertificationKey(data, passphrase)
    }

    func extractPrimaryRSACertificationKey(fromSecretKeyData data: Data, passphrase: String? = nil) throws -> RSASigningInfo {
        guard let unlock = Self.secretKeyUnlock else { throw PGPServiceError.unlockUnavailable }
        return try unlock.primaryRSACertificationKey(data, passphrase)
    }

    // MARK: - 7.1.1 Cv25519 Scalar Byte-Order Resolution

    /// Which byte order a stored/wire Cv25519 secret scalar turned out to be
    /// in, as proven by the public-point consistency check.
    enum Cv25519ScalarByteOrder {
        /// RFC 9580 big-endian MPI — GnuPG / Sequoia / BouncyCastle origin,
        /// or generated by PGPony 7.1.1 and later.
        case canonicalBE
        /// CryptoKit `rawRepresentation` little-endian written straight into
        /// the packet — PGPony's pre-7.1.1 generator.
        case legacyLE
    }

    /// Left-pad a byte buffer with zeros to 32 bytes. Restores leading zero
    /// bytes that canonical MPI encoding strips (big-endian semantics put
    /// them back on the front). Buffers already >= 32 bytes are returned
    /// unchanged.
    static func leftPad32(_ bytes: [UInt8]) -> [UInt8] {
        guard bytes.count < 32 else { return bytes }
        return [UInt8](repeating: 0, count: 32 - bytes.count) + bytes
    }

    /// Derive the X25519 public point for a candidate little-endian scalar.
    /// CryptoKit clamps internally before the scalar multiplication, so this
    /// check is deliberately clamp-INSENSITIVE — a clamped and an unclamped
    /// copy of the same scalar produce the same point. That is exactly the
    /// property that lets one check accept both PGPony's historical
    /// unclamped-LE storage and the canonical clamped-BE wire form.
    static func derivedCv25519PublicKey(fromLEScalar leScalar: [UInt8]) -> [UInt8]? {
        guard leScalar.count == 32,
              let key = try? Curve25519.KeyAgreement.PrivateKey(rawRepresentation: Data(leScalar))
        else { return nil }
        return Array(key.publicKey.rawRepresentation)
    }

    /// Resolve which byte order a Cv25519 secret scalar was serialized in by
    /// testing candidate interpretations against the subkey's public point
    /// (the packet's own ground truth). Candidates, in order:
    ///
    ///   1. `reversed(leftPad32(wireBytes))` — the CANONICAL reading: the
    ///      MPI is big-endian, so reversing yields the little-endian scalar
    ///      CryptoKit wants. Tried first so correctly encoded keys resolve
    ///      on the first derivation.
    ///   2. `wireBytes` as-is — the LEGACY reading: pre-7.1.1 PGPony wrote
    ///      the little-endian buffer without reversing.
    ///   3. `physical32` as-is, when the caller captured a full 32-byte
    ///      physical region that disagrees with the MPI header — rescues
    ///      legacy keys whose header claimed fewer bits than the appended
    ///      bytes (the pre-7.1.1 dBits bug, ~1 in 32 keys).
    ///
    /// Returns the resolved little-endian scalar plus which order matched,
    /// or nil if NO interpretation reproduces the public point — the caller
    /// must treat nil as corrupted key material, never guess.
    static func resolveCv25519Scalar(
        wireBytes: [UInt8],
        physical32: [UInt8]?,
        publicPoint: [UInt8]
    ) -> (order: Cv25519ScalarByteOrder, leScalar: [UInt8])? {
        guard !publicPoint.isEmpty else { return nil }

        let padded = leftPad32(wireBytes)
        if padded.count == 32 {
            let canonicalLE: [UInt8] = padded.reversed()
            if derivedCv25519PublicKey(fromLEScalar: canonicalLE) == publicPoint {
                return (.canonicalBE, canonicalLE)
            }
            if derivedCv25519PublicKey(fromLEScalar: padded) == publicPoint {
                return (.legacyLE, padded)
            }
        }

        if let physical = physical32, physical.count == 32, physical != padded {
            let physicalReversed: [UInt8] = physical.reversed()
            if derivedCv25519PublicKey(fromLEScalar: physicalReversed) == publicPoint {
                return (.canonicalBE, physicalReversed)
            }
            if derivedCv25519PublicKey(fromLEScalar: physical) == publicPoint {
                return (.legacyLE, physical)
            }
        }

        return nil
    }

    /// Decrypt v6 AEAD-protected secret key material.
    ///
    /// Parses the S2K usage 253 fields (cipher, AEAD algo, Argon2 S2K specifier,
    /// nonce) and decrypts using Argon2 + AEAD.
    ///
    /// V6 S2K 253 layout after s2k_usage byte:
    ///   optional_fields_count(1) — total bytes of cipher+aead+s2k fields
    ///   cipher_algo(1)
    ///   aead_algo(1)
    ///   s2k_count(1) — byte count of S2K specifier
    ///   s2k_specifier: type(1)=4 | salt(16) | t(1) | p(1) | m(1)
    ///   nonce (AEAD-dependent: OCB=15, GCM=12, EAX=16)
    ///   encrypted_material + tag(16)
    func decryptV6SecretKeyMaterial(
        body: [UInt8],
        offset: inout Int,
        publicBody: [UInt8],
        packetTagID: UInt8,
        passphrase: String,
        expectedKeyLen: Int
    ) throws -> [UInt8] {
        // Optional fields count (v6 length #1) — cumulative length of cipher-algo,
        // AEAD-algo, the S2K-specifier length octet, the S2K specifier, AND the
        // nonce (RFC 9580 §5.5.3: the IV is one of the conditional S2K fields).
        guard offset < body.count else {
            throw PGPServiceError.decryptionFailed(String(localized: "V6 secret key: missing optional fields count"))
        }
        let optFieldsCount = Int(body[offset]); offset += 1
        let optFieldsStart = offset

        pgpDebugLog("DEBUG V6 S2K253: optFieldsCount=\(optFieldsCount)")

        // Cipher algorithm
        guard offset < body.count else {
            throw PGPServiceError.decryptionFailed(String(localized: "V6 secret key: missing cipher algo"))
        }
        let cipherAlgo = body[offset]; offset += 1

        // AEAD algorithm
        guard offset < body.count else {
            throw PGPServiceError.decryptionFailed(String(localized: "V6 secret key: missing AEAD algo"))
        }
        let aeadAlgo = body[offset]; offset += 1

        // S2K specifier length (v6 length #2)
        guard offset < body.count else {
            throw PGPServiceError.decryptionFailed(String(localized: "V6 secret key: missing S2K length"))
        }
        let s2kLen = Int(body[offset]); offset += 1

        pgpDebugLog("DEBUG V6 S2K253: cipher=\(cipherAlgo), aead=\(aeadAlgo) (1=EAX,2=OCB,3=GCM), s2kLen=\(s2kLen)")

        // S2K specifier
        guard offset + s2kLen <= body.count, s2kLen >= 1 else {
            throw PGPServiceError.decryptionFailed(String(localized: "V6 secret key: S2K specifier truncated"))
        }
        let s2kType = body[offset]

        // S2K parameters, populated per type below. Sequoia (rfc9580 profile)
        // protects composite secret keys with iterated+salted (type 3); GnuPG/
        // RFC 9580's own examples use Argon2 (type 4). Support both — the AEAD
        // unlock path downstream is identical.
        var argon2Salt: [UInt8] = []
        var argon2T = 0, argon2P = 0, argon2M = 0
        var iterSalt: [UInt8] = []
        var iterHashAlgo: UInt8 = 0
        var iterCoded: UInt8 = 0

        switch s2kType {
        case 4:
            // Argon2 specifier: type(1)=4 | salt(16) | t(1) | p(1) | encoded_m(1) = 20 octets
            guard s2kLen == 20, offset + 20 <= body.count else {
                throw PGPServiceError.decryptionFailed(String(localized: "V6 secret key: Argon2 specifier must be 20 octets"))
            }
            argon2Salt = Array(body[(offset + 1)..<(offset + 17)])
            argon2T = Int(body[offset + 17])     // passes
            argon2P = Int(body[offset + 18])     // parallelism
            argon2M = Int(body[offset + 19])     // memory exponent (2^m KiB)
            pgpDebugLog("DEBUG V6 Argon2: salt=\(argon2Salt.map { String(format: "%02x", $0) }.joined()), t=\(argon2T), p=\(argon2P), m=\(argon2M) (2^\(argon2M) KiB = \(1 << argon2M) KiB)")

        case 3:
            // Iterated+salted specifier: type(1)=3 | hash(1) | salt(8) | coded-count(1) = 11 octets
            guard s2kLen == 11, offset + 11 <= body.count else {
                throw PGPServiceError.decryptionFailed(String(localized: "V6 secret key: iterated+salted specifier must be 11 octets"))
            }
            iterHashAlgo = body[offset + 1]
            iterSalt = Array(body[(offset + 2)..<(offset + 10)])
            iterCoded = body[offset + 10]
            pgpDebugLog("DEBUG V6 S2K3: hash=\(iterHashAlgo), salt=\(iterSalt.map { String(format: "%02x", $0) }.joined()), coded=\(iterCoded)")

        default:
            throw PGPServiceError.decryptionFailed(String(localized: "V6 secret key: expected S2K type 3 or 4, got type \(String(describing: s2kType))"))
        }
        offset += s2kLen

        // AEAD nonce — immediately follows the S2K specifier (it is the LAST of the
        // conditional fields counted by optFieldsCount; do NOT skip ahead by
        // optFieldsCount, which would skip over the nonce itself).
        let nonceLen = AEADService.nonceSize(for: aeadAlgo)
        guard nonceLen > 0 else {
            throw PGPServiceError.decryptionFailed(String(localized: "V6 secret key: unsupported AEAD algo \(String(describing: aeadAlgo))"))
        }
        guard offset + nonceLen <= body.count else {
            throw PGPServiceError.decryptionFailed(String(localized: "V6 secret key: nonce truncated"))
        }
        let nonce = Array(body[offset..<(offset + nonceLen)]); offset += nonceLen

        // Sanity-check the declared cumulative length against what we consumed.
        let consumedParams = offset - optFieldsStart
        if optFieldsCount != consumedParams {
            pgpDebugLog("DEBUG V6 S2K253: WARNING optFieldsCount=\(optFieldsCount) but consumed \(consumedParams) (cipher+aead+len+spec+nonce)")
        }

        pgpDebugLog("DEBUG V6 AEAD: nonce=\(nonce.map { String(format: "%02x", $0) }.joined()) (\(nonceLen) bytes)")

        // Encrypted material + AEAD tag = rest of body
        let encryptedWithTag = Array(body[offset...])
        guard encryptedWithTag.count >= AEADService.tagSize else {
            throw PGPServiceError.decryptionFailed(String(localized: "V6 secret key: encrypted data too short for AEAD tag"))
        }

        pgpDebugLog("DEBUG V6 AEAD: encrypted+tag = \(encryptedWithTag.count) bytes (expected key=\(expectedKeyLen) + tag=16 = \(expectedKeyLen + 16))")

        // Derive S2K key from passphrase.
        let keySize = try s2kCipherKeySize(cipherAlgo)
        let s2kKey: [UInt8]
        switch s2kType {
        case 4:
            s2kKey = try Argon2Service.deriveKey(
                passphrase: passphrase,
                salt: argon2Salt,
                iterations: argon2T,
                parallelism: argon2P,
                memoryExponent: argon2M,
                hashLength: keySize
            )
        case 3:
            s2kKey = S2K.deriveKey(
                passphrase: passphrase,
                salt: iterSalt,
                s2kType: 3,
                hashAlgo: iterHashAlgo,
                codedCount: iterCoded,
                keySize: keySize
            )
        default:
            throw PGPServiceError.decryptionFailed(String(localized: "V6 secret key: unsupported S2K type \(String(describing: s2kType))"))
        }

        // KEK = HKDF-SHA256(IKM = S2K key, no salt,
        //                   info = [packetTagID, 0x06, cipher-algo, AEAD-algo]).
        // RFC 9580 §5.5.3 ¶9 — provides key separation between cipher/AEAD.
        let info: [UInt8] = [packetTagID, 0x06, cipherAlgo, aeadAlgo]
        let kek = try OpenPGPPacketParser.hkdfSHA256(
            ikm: s2kKey, salt: [], info: info, outputLength: keySize
        )

        pgpDebugLog("DEBUG V6 Argon2: derived \(s2kKey.count)-byte S2K key and the \(kek.count)-byte KEK")

        // AAD = packetTagID || public-key packet body (from the version octet).
        let aad: [UInt8] = [packetTagID] + publicBody

        // Decrypt with AEAD (single chunk, tag appended). At this point all
        // parameters parsed cleanly, so an authentication-tag failure means the
        // derived KEK is wrong — i.e. the passphrase is wrong. Surface it as
        // invalidPassphrase so the caller re-prompts, rather than letting the raw
        // AEAD error bubble up and be misreported as "no matching decryption key".
        let decrypted: [UInt8]
        do {
            decrypted = try AEADService.decryptWithAppendedTag(
                data: encryptedWithTag,
                key: kek,
                nonce: nonce,
                aeadAlgo: aeadAlgo,
                associatedData: aad
            )
        } catch {
            pgpDebugLog("DEBUG V6 AEAD: tag verification failed (\(error)) — treating as wrong passphrase")
            throw PGPServiceError.invalidPassphrase
        }

        pgpDebugLog("DEBUG V6 AEAD: decrypted \(decrypted.count) bytes")

        // V6 secret key material is raw bytes (no MPI wrapping, no checksum).
        // For X25519/Ed25519: exactly 32 bytes.
        guard decrypted.count == expectedKeyLen else {
            pgpDebugLog("DEBUG V6 AEAD: expected \(expectedKeyLen) bytes, got \(decrypted.count) — possible wrong passphrase")
            throw PGPServiceError.invalidPassphrase
        }

        return decrypted
    }

    /// Get AES key size from OpenPGP cipher ID
    fileprivate func s2kCipherKeySize(_ cipherID: UInt8) throws -> Int {
        switch cipherID {
        case 7: return 16   // AES-128
        case 8: return 24   // AES-192
        case 9: return 32   // AES-256
        default: throw PGPServiceError.decryptionFailed(String(localized: "Unsupported S2K cipher: \(String(describing: cipherID))"))
        }
    }
}

enum PGPServiceError: LocalizedError {
    case keyGenerationFailed(String)
    case encryptionFailed(String)
    case decryptionFailed(String)
    case signingFailed(String)
    case verificationFailed(String)
    case keyNotFound
    case invalidKeyData
    case importFailed(String)
    case exportFailed(String)
    case passphraseRequired
    case invalidPassphrase
    // 7.1.1 — exporting a passphrase-protected Cv25519 secret subkey requires
    // decrypting the S2K blob to verify (and, for legacy keys, normalize) the
    // scalar byte order, so the export path can now ask for the passphrase.
    case exportPassphraseRequired
    // 7.1.1 — the secret scalar failed the public-point consistency check in
    // BOTH byte orders. Exporting it would produce a backup that can never
    // decrypt anything, so the export refuses instead.
    case exportIntegrityFailed(String)
    // CORE SEAM: no secret-key unlock was provided by the host (see PGPService.secretKeyUnlock).
    case unlockUnavailable
    
    var errorDescription: String? {
        switch self {
        case .keyGenerationFailed(let msg): return String(localized: "Key generation failed: \(msg)")
        case .encryptionFailed(let msg): return String(localized: "Encryption failed: \(msg)")
        case .decryptionFailed(let msg): return String(localized: "Decryption failed: \(msg)")
        case .signingFailed(let msg): return String(localized: "Signing failed: \(msg)")
        case .verificationFailed(let msg): return String(localized: "Verification failed: \(msg)")
        case .keyNotFound: return String(localized: "Key not found in keyring")
        case .invalidKeyData: return String(localized: "Invalid key data")
        case .importFailed(let msg): return String(localized: "Import failed: \(msg)")
        case .exportFailed(let msg): return String(localized: "Export failed: \(msg)")
        case .passphraseRequired: return String(localized: "Passphrase is required for this key")
        case .invalidPassphrase: return String(localized: "Incorrect Passphrase")
        case .exportPassphraseRequired: return String(localized: "The key's passphrase is required to export it")
        case .exportIntegrityFailed(let msg): return String(localized: "Key export integrity check failed: \(msg)")
        case .unlockUnavailable: return String(localized: "This build cannot unlock secret keys.")
        }
    }
}

// CORE SEAM: the app's KeyringDeduplicationService works over SwiftData; the
// core keeps its fingerprint normalization, which CertificationService uses.
enum KeyringDeduplicationService {
    /// Canonical form for fingerprint equality: bare lowercase hex. Every
    /// producer in the app emits bare hex (the native parser via
    /// String(format: "%02x"), ObjectivePGP via description()), so matching is
    /// case-insensitive hex equality; whitespace is stripped defensively in
    /// case a display-formatted fingerprint ever reaches an import path.
    static func normalize(_ fingerprint: String) -> String {
        fingerprint.lowercased().filter { !$0.isWhitespace }
    }
}

// CORE SEAM: the app's PublicKeyBundle gathers a key's public ring from the
// Keychain; the core keeps its armor writer, which SelfSignatureRefresh uses.
enum PublicKeyBundle {
    /// Header-free PUBLIC KEY BLOCK armor, 64-column base64 and the CRC-24
    /// checksum (RFC 4880 6).
    static func armorPublicKeyBlock(_ data: [UInt8]) -> String {
        let b64 = Data(data).base64EncodedString(options: .lineLength64Characters)
            .replacingOccurrences(of: "\r\n", with: "\n")
        let crc = Data(crc24(data)).base64EncodedString()
        return "-----BEGIN PGP PUBLIC KEY BLOCK-----\n\n\(b64)\n=\(crc)\n-----END PGP PUBLIC KEY BLOCK-----\n"
    }

    private static func crc24(_ data: [UInt8]) -> [UInt8] {
        var crc: UInt32 = 0xB704CE
        for byte in data {
            crc ^= UInt32(byte) << 16
            for _ in 0..<8 {
                crc <<= 1
                if crc & 0x1000000 != 0 { crc ^= 0x1864CFB }
            }
        }
        crc &= 0xFFFFFF
        return [UInt8((crc >> 16) & 0xFF), UInt8((crc >> 8) & 0xFF), UInt8(crc & 0xFF)]
    }
}

// CORE SEAM: lifted verbatim from the app's ProgressReporter.swift, for the
// key editors that unlock and sign off the main thread.
/// Run blocking work on a background queue and await the result.
///
/// v8.1.0 §3a — this exists because `Task.detached` did not do it. Encrypting a
/// 156 MB file reported progress with `Thread.isMainThread == true`, which means
/// the whole encryption ran on the main thread: the UI was frozen for its
/// duration, and no progress mechanism could have worked, because there was no
/// main thread available to deliver to. Three attempts at fixing the progress
/// bar were all treating the symptom.
///
/// `DispatchQueue.global` is not subject to whatever inference or isolation
/// caused that — a global queue is never the main thread. Where correctness
/// depends on being off the main thread, being explicit beats being idiomatic.
func runOffMainThread<T>(_ work: @escaping () throws -> T) async throws -> T {
    try await withCheckedThrowingContinuation { (continuation: CheckedContinuation<T, Error>) in
        DispatchQueue.global(qos: .userInitiated).async {
            do {
                continuation.resume(returning: try work())
            } catch {
                continuation.resume(throwing: error)
            }
        }
    }
}
